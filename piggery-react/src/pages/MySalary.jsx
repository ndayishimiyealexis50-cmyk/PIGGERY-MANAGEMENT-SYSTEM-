const card = {
  padding: 12,
  borderRadius: 12,
  background: 'rgba(128,128,128,0.12)',
  border: '1px solid rgba(128,128,128,0.25)',
}

export default function MySalary({ user, salaries }) {
  const mine = (salaries || [])
    .filter(s => s.workerId === user?.uid || s.workerId === user?.id)
    .filter(s => !(s.autoGenerated && !s.admin && s.status === "pending"))
    .sort((a, b) => String(b.dueDate || '').localeCompare(String(a.dueDate || '')))
  const amt = s => Number(s.net || s.amount || 0)
  const total = list => list.reduce((a, s) => a + amt(s), 0)
  const paid = mine.filter(s => s.status === 'paid')
  const pending = mine.filter(s => s.status === 'pending')
  const day = d => (d ? String(d).slice(0, 10) : '-')

  return (
    <div style={{ padding: 16 }}>
      <h2 style={{ margin: '0 0 12px' }}>My Salary</h2>
      <div style={{ display: 'flex', gap: 10, marginBottom: 16 }}>
        <div style={{ ...card, flex: 1 }}>
          <div style={{ fontSize: 12, opacity: 0.7 }}>Pending</div>
          <div style={{ fontSize: 18, fontWeight: 700, color: '#f59e0b' }}>{total(pending).toLocaleString()} RWF</div>
        </div>
        <div style={{ ...card, flex: 1 }}>
          <div style={{ fontSize: 12, opacity: 0.7 }}>Paid</div>
          <div style={{ fontSize: 18, fontWeight: 700, color: '#16a34a' }}>{total(paid).toLocaleString()} RWF</div>
        </div>
      </div>
      {mine.length === 0 && <div style={card}>No salary records yet.</div>}
      {mine.map((s, i) => (
        <div key={s.id || i} style={{ ...card, marginBottom: 10 }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <strong>{amt(s).toLocaleString()} RWF</strong>
            <span style={{ padding: '3px 10px', borderRadius: 999, fontSize: 12, fontWeight: 700, color: '#fff', background: s.status === 'paid' ? '#16a34a' : '#f59e0b' }}>
              {s.status === 'paid' ? 'Paid' : 'Pending'}
            </span>
          </div>
          <div style={{ fontSize: 12, opacity: 0.75, marginTop: 6 }}>
            Due: {day(s.dueDate)}
            {s.status === 'paid' && <> · Paid on: {day(s.paidAt)}</>}
          </div>
        </div>
      ))}
    </div>
  )
}
